/* Builds pewtalk-data.js from scripts/pew-talk-cards.mjs and the app's own
   KJV and RV1909 files, so every linked verse is the exact text the reader shows.
   Run: node scripts/build-pew-talk.mjs */
import { readFileSync, writeFileSync } from 'node:fs';
import { CARDS, CATEGORIES } from './pew-talk-cards.mjs';
const root = new URL('../', import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const enIndex = read('bible/index.json').books, esIndex = read('bible/rvr/index.json').books;
const pad = (n) => String(n).padStart(2, '0');
const cache = {};
const book = (dir, n) => (cache[dir + n] ||= read(`${dir}${pad(n)}.json`));
const cards = CARDS.map(([id, cat, en, es, b, c, v]) => {
  if (!CATEGORIES[cat]) throw Error(`${id}: unknown category ${cat}`);
  const kjv = book('bible/', b).chapters[c - 1]?.[v - 1], rv = book('bible/rvr/', b).chapters[c - 1]?.[v - 1];
  if (!kjv || !rv) throw Error(`${id}: verse ${b} ${c}:${v} missing`);
  const nameEn = enIndex.find((x) => x.id === b).name, nameEs = esIndex.find((x) => x.id === b).name;
  return { id, cat, en, es, ref: { book: b, chapter: c, verse: v, en: `${nameEn} ${c}:${v}`, es: `${nameEs} ${c}:${v}`, textEn: kjv.trim(), textEs: rv.trim() } };
});
const ids = new Set(cards.map((x) => x.id));
if (ids.size !== cards.length) throw Error('duplicate card id');
const out = `/* Pew Talk card deck. Generated by scripts/build-pew-talk.mjs. Do not edit by hand. */
window.MsbPewTalkData = ${JSON.stringify({ categories: CATEGORIES, cards }, null, 1)};
`;
writeFileSync(new URL('pewtalk-data.js', root), out);
console.log(`pewtalk-data.js: ${cards.length} cards`);
